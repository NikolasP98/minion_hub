/**
 * `dev:local --gateway` / `qa:up --gateway` — the local Minion gateway.
 *
 * Spec: meta-repo `specs/011-dev-local-gateway-mode/`.
 *
 * The QA stack deliberately blanks every outbound-service credential
 * (scripts/qa/env.ts:94-107), gateway URL/token included, so the dashboard's
 * floating assistant is offline on a local dev server. This module is the
 * opt-in escape hatch: it runs the published gateway image as an extra
 * service in the SAME `hub-qa` compose project (behind compose profile
 * "gateway", so the default path cannot start it), with a token this stack
 * mints for itself.
 *
 * Secret boundary — read this before changing anything here: `--gateway` is
 * the ONE place a developer-held secret enters the QA stack. The model
 * provider keys are read out of the developer's own environment and handed
 * only to the gateway container; `.env.qa` still writes them empty, so the
 * hub process itself stays keyless. Nothing else in
 * OUTBOUND_SERVICE_ENV_KEYS is un-blanked.
 *
 * Networking: `network_mode: host`, like the `hub` service — the browser
 * reaches the gateway at ws://127.0.0.1:18789 and the gateway reaches the
 * host dev server at http://127.0.0.1:5199, with no host.docker.internal and
 * no bridge-IP discovery. Linux-only, matching docker-compose.qa.yml.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';

/** The gateway's HTTP/WS port. The image's own CMD and healthcheck both use
 *  18789 (minion/Dockerfile); `DEFAULT_BRIDGE_PORT = 18790` is referenced only
 *  in minion/src/config/port-defaults.ts and tests — nothing binds it. The
 *  `http://127.0.0.1:18790` in scripts/qa/seed/gateway-libsql.ts is a legacy
 *  Turso-mirror row the hub does not read; left alone deliberately. */
export const GATEWAY_PORT = 18789;
export const GATEWAY_WS_URL = `ws://127.0.0.1:${GATEWAY_PORT}`;
export const GATEWAY_HTTP_URL = `http://127.0.0.1:${GATEWAY_PORT}`;
/** Published image. Override with $MINION_GATEWAY_IMAGE for a local build. */
export const GATEWAY_IMAGE = 'ghcr.io/nikolasp98/minion-ai:dev';
/** Stable `gateway.legacy_server_id` for the local row — the id the dashboard
 *  keys hosts by and the gateway sends back as its serverId. */
export const LOCAL_SERVER_ID = 'qa-local-gateway';
export const LOCAL_GATEWAY_NAME = 'QA Local Gateway';
/** The host dev server, for the gateway's hub callbacks (hubMetrics below). */
export const HUB_CALLBACK_URL = 'http://127.0.0.1:5199';

const TAG = 'qa:gateway';

/** Model-provider keys forwarded into the container. The gateway's default
 *  model alias is an Anthropic one and there is NO fallback to OpenRouter for
 *  it (minion/src/config/defaults.ts, minion/src/providers/registry.ts), so
 *  ANTHROPIC_API_KEY is the one that makes replies work; OPENROUTER_API_KEY is
 *  forwarded too because the gateway's memory/web-search paths use it. */
export const PROVIDER_ENV_KEYS = ['ANTHROPIC_API_KEY', 'OPENROUTER_API_KEY'] as const;

/** Pure: the provider keys present and non-empty in `env`, nothing else.
 *  Called BEFORE ignoreInheritedBackendEnv() deletes them (scripts/qa/dev.ts). */
export function collectProviderKeys(env: NodeJS.ProcessEnv): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of PROVIDER_ENV_KEYS) {
    const raw = env[key]?.trim();
    if (raw) out[key] = raw;
  }
  return out;
}

/** Pure: the five gateway names `.env.qa` normally writes empty, resolved to
 *  the local stack. The broadcast URL is http (cache fan-out is a POST), the
 *  rest are the WS URL the dashboard dials. */
export function buildGatewayEnvVars(token: string): Record<string, string> {
  return {
    MINION_GATEWAY_URL: GATEWAY_WS_URL,
    OPENCLAW_GATEWAY_URL: GATEWAY_WS_URL,
    MINION_GATEWAY_PRIMARY_URL: GATEWAY_WS_URL,
    MINION_GATEWAY_BROADCAST_URL: GATEWAY_HTTP_URL,
    OPENCLAW_GATEWAY_TOKEN: token,
  };
}

/** Pure: the container's env file body (compose `env_file`). */
export function buildGatewayEnvFile(token: string, providerKeys: Record<string, string>): string {
  return [
    '# Generated by `bun run dev:local --gateway` — do not edit by hand.',
    '# Loaded by docker-compose.qa.yml service `minion-gateway`.',
    `MINION_GATEWAY_TOKEN=${token}`,
    `MINION_GATEWAY_IMAGE=${process.env.MINION_GATEWAY_IMAGE ?? GATEWAY_IMAGE}`,
    '# --- the ONE developer secret boundary of the QA stack (see module header) ---',
    ...PROVIDER_ENV_KEYS.map((key) => `${key}=${providerKeys[key] ?? ''}`),
    '',
  ].join('\n');
}

/** Pure: the gateway's `minion.json`. `base` is the image's own
 *  docker/default-config.json (extracted at run time, so this never drifts
 *  from the image); the only thing added is `gateway.hubMetrics`, which is the
 *  ONLY way the gateway learns to call the hub back — it reads no hub env var
 *  (minion/src/gateway/hub-metrics-config.ts). `apiKey` is the gateway token:
 *  the hub matches an inbound bearer token against `gateway.token_ciphertext`
 *  and takes the org from that row (src/server/auth/resolve-identity.ts:114). */
export function buildGatewayConfig(
  base: Record<string, unknown>,
  opts: { hubUrl: string; token: string; serverId: string },
): Record<string, unknown> {
  const gateway = { ...((base.gateway as Record<string, unknown>) ?? {}) };
  gateway.hubMetrics = { hubUrl: opts.hubUrl, apiKey: opts.token, serverId: opts.serverId };
  return { ...base, gateway };
}

/** Load-or-create the per-stack gateway shared secret. Same contract as
 *  `loadOrCreateEncryptionKey` in scripts/qa/env.ts: stable across re-runs
 *  (rows sealed by a previous run stay valid), mode 600, outside git. */
export function loadOrCreateGatewayToken(root: string): string {
  const file = join(root, '.qa', 'gateway-token');
  if (existsSync(file)) {
    const existing = readFileSync(file, 'utf8').trim();
    if (existing) return existing;
  }
  mkdirSync(join(root, '.qa'), { recursive: true });
  const token = randomBytes(32).toString('hex');
  writeFileSync(file, token + '\n', { mode: 0o600 });
  chmodSync(file, 0o600);
  return token;
}

/** The image's own default config, read out of the image rather than copied
 *  into this repo. Returns `{}` (and warns) if the image cannot be read — the
 *  container's entrypoint then writes its own default and only hubMetrics is
 *  lost, which is a legible degradation rather than a broken config. */
export function readImageDefaultConfig(image: string): Record<string, unknown> {
  const r = spawnSync(
    'docker',
    ['run', '--rm', '--entrypoint', 'cat', image, '/app/docker/default-config.json'],
    { encoding: 'utf8' },
  );
  if (r.status !== 0) {
    console.warn(
      `${TAG} — could not read /app/docker/default-config.json from ${image}: ${r.stderr?.trim() || 'unknown error'}`,
    );
    return {};
  }
  try {
    return JSON.parse(r.stdout) as Record<string, unknown>;
  } catch (err) {
    console.warn(`${TAG} — ${image}'s default config is not valid JSON: ${String(err)}`);
    return {};
  }
}

/** Probe the gateway's /health until it answers or the budget runs out. */
export async function waitForGatewayHealth(timeoutMs = 120_000): Promise<boolean> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${GATEWAY_HTTP_URL}/health`, {
        signal: AbortSignal.timeout(3000),
      });
      if (res.ok) return true;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 2000));
  }
  return false;
}

/**
 * Bring the `minion-gateway` service up in the existing `hub-qa` compose
 * project. Only ever `up -d minion-gateway` — never `down`, never `reset`,
 * never an unscoped `up` — because the Supabase containers of this project
 * are shared with any other checkout running against the same stack.
 */
export async function ensureGatewayStack(
  root: string,
  composeFile: string,
  opts: { token: string; providerKeys: Record<string, string> },
): Promise<void> {
  const image = process.env.MINION_GATEWAY_IMAGE ?? GATEWAY_IMAGE;

  const envFile = join(root, '.env.qa.gateway');
  writeFileSync(envFile, buildGatewayEnvFile(opts.token, opts.providerKeys), { mode: 0o600 });
  chmodSync(envFile, 0o600);

  const stateDir = join(root, 'data', 'qa', 'gateway');
  mkdirSync(join(stateDir, 'workspace'), { recursive: true });
  const configPath = join(stateDir, 'minion.json');
  // Written BEFORE first boot: the image's entrypoint copies its default
  // config only when this file is absent, so writing it first is how
  // hubMetrics gets in without a second pass + restart.
  if (!existsSync(configPath)) {
    const config = buildGatewayConfig(readImageDefaultConfig(image), {
      hubUrl: HUB_CALLBACK_URL,
      token: opts.token,
      serverId: LOCAL_SERVER_ID,
    });
    writeFileSync(configPath, JSON.stringify(config, null, 2) + '\n', { mode: 0o644 });
  }

  if (!Object.keys(opts.providerKeys).length) {
    console.warn(
      `${TAG} — no model-provider key found in your environment (${PROVIDER_ENV_KEYS.join(', ')}). ` +
        'The gateway will start and the assistant will connect, but replies will fail. ' +
        'Put ANTHROPIC_API_KEY in your .env.local to fix it.',
    );
  }

  console.log(`${TAG} — starting ${image} on ${GATEWAY_WS_URL} (compose profile "gateway")`);
  const up = spawnSync(
    'docker',
    ['compose', '-f', composeFile, '--profile', 'gateway', 'up', '-d', 'minion-gateway'],
    { cwd: root, stdio: 'inherit' },
  );
  if (up.status !== 0) {
    throw new Error(
      `${TAG} — \`docker compose up -d minion-gateway\` failed (exit ${up.status}). ` +
        `Is ${image} pullable from here? Try \`docker manifest inspect ${image}\`.`,
    );
  }

  if (!(await waitForGatewayHealth())) {
    throw new Error(
      `${TAG} — ${GATEWAY_HTTP_URL}/health never answered. ` +
        `Check \`docker compose -f ${composeFile} logs minion-gateway\`, and that nothing else holds port ${GATEWAY_PORT}.`,
    );
  }
  console.log(`${TAG} — gateway healthy at ${GATEWAY_HTTP_URL}`);
}
