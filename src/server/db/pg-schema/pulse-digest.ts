import {
  pgTable,
  text,
  uuid,
  integer,
  bigint,
  boolean,
  timestamp,
  jsonb,
  date,
  primaryKey,
} from 'drizzle-orm/pg-core';
import type { DigestSnapshot } from '$server/services/pulse-digest.sources';
export const pulseDigestAdmission = pgTable(
  'pulse_digest_admission',
  {
    orgId: text('org_id').notNull(),
    ownerProfileId: text('owner_profile_id').notNull(),
    budgetNamespace: text('budget_namespace').notNull(),
    policyRevision: text('policy_revision').notNull(),
    policyHash: text('policy_hash').notNull(),
    enabled: boolean('enabled').notNull().default(false),
    approvalRevision: text('approval_revision').notNull(),
    approvalExpiresAt: timestamp('approval_expires_at', { withTimezone: true }).notNull(),
    maxCalls: integer('max_calls').notNull(),
    upperMicroUsd: bigint('upper_micro_usd', { mode: 'number' }).notNull(),
    dailyMicroUsd: bigint('daily_micro_usd', { mode: 'number' }).notNull(),
    budgetDay: date('budget_day').notNull(),
    attemptedCalls: integer('attempted_calls').notNull().default(0),
    reservedMicroUsd: bigint('reserved_micro_usd', { mode: 'number' }).notNull().default(0),
    settledMicroUsd: bigint('settled_micro_usd', { mode: 'number' }).notNull().default(0),
    unknownExposureFence: boolean('unknown_exposure_fence').notNull().default(false),
    activeRunId: uuid('active_run_id'),
    activeAttemptId: uuid('active_attempt_id'),
    admissionGeneration: integer('admission_generation').notNull().default(0),
    nextPollAt: timestamp('next_poll_at', { withTimezone: true }).notNull().defaultNow(),
    collectionOwner: uuid('collection_owner'),
    collectionGeneration: integer('collection_generation').notNull().default(0),
    collectionLeaseUntil: timestamp('collection_lease_until', { withTimezone: true }),
    lastCollectionOutcome: text('last_collection_outcome'),
    lastCollectionAt: timestamp('last_collection_at', { withTimezone: true }),
    retiredAt: timestamp('retired_at', { withTimezone: true }),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.orgId, t.ownerProfileId, t.budgetNamespace] })],
);
export const pulseDigestRuns = pgTable('pulse_digest_runs', {
  sourceRevisions: jsonb('source_revisions')
    .$type<{ sourceId: string; revision: number; contentHash: string }[]>()
    .notNull()
    .default([]),
  id: uuid('id').primaryKey().defaultRandom(),
  orgId: text('org_id').notNull(),
  ownerProfileId: text('owner_profile_id').notNull(),
  budgetNamespace: text('budget_namespace').notNull(),
  policyRevision: text('policy_revision').notNull(),
  policyHash: text('policy_hash').notNull(),
  sourceSnapshotHash: text('source_snapshot_hash').notNull(),
  requestHash: text('request_hash').notNull(),
  snapshot: jsonb('snapshot').$type<DigestSnapshot>(),
  evidence: text('evidence'),
  requestedModel: text('requested_model').notNull(),
  resolvedModel: text('resolved_model'),
  bgJobId: text('bg_job_id').notNull(),
  state: text('state').notNull().default('queued'),
  attemptId: uuid('attempt_id'),
  admittedGeneration: integer('admitted_generation'),
  admittedDay: date('admitted_day'),
  admittedAt: timestamp('admitted_at', { withTimezone: true }),
  upperMicroUsd: bigint('upper_micro_usd', { mode: 'number' }),
  rawResponse: text('raw_response'),
  receiptHash: text('receipt_hash'),
  usageStatus: text('usage_status'),
  costMicroUsd: bigint('cost_micro_usd', { mode: 'number' }),
  receiptMetadata: jsonb('receipt_metadata').$type<Record<string, unknown>>(),
  result: jsonb('result').$type<Record<string, unknown>>(),
  resultHash: text('result_hash'),
  cardId: uuid('card_id'),
  safeReason: text('safe_reason'),
  attemptCount: integer('attempt_count').notNull().default(0),
  nextAttemptAt: bigint('next_attempt_at', { mode: 'number' }),
  redactedAt: timestamp('redacted_at', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});
export type DigestRun = typeof pulseDigestRuns.$inferSelect;
export const pulseDigestSources = pgTable(
  'pulse_digest_sources',
  {
    orgId: text('org_id').notNull(),
    ownerProfileId: text('owner_profile_id').notNull(),
    policyRevision: text('policy_revision').notNull(),
    sourceId: text('source_id').notNull(),
    revision: integer('revision').notNull().default(0),
    contentHash: text('content_hash'),
    etag: text('etag'),
    lastModified: text('last_modified'),
    evidence: jsonb('evidence').$type<DigestSnapshot['evidence']>(),
    lastRunId: uuid('last_run_id'),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.orgId, t.ownerProfileId, t.policyRevision, t.sourceId] })],
);
